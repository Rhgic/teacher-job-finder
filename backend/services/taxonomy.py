"""岗位分类标准表（学科 / 学段 / 区域）。

唯一事实源：爬虫用它从公告文本里识别字段，接口用它给前端提供可选项。
两处共用一份定义，避免"爬虫认得的值前端选不到"这类分叉。

注意与"数据里出现过的值"的区别：
- 岗位页筛选用**数据推导**的值——筛一个 0 结果的学科没有意义。
- 订阅规则用**这里的标准表**——规则要匹配的是将来爬到的岗位，
  库里当前没有体育岗位，不代表体育老师不能表达求职意向。
"""

# 覆盖中小学常见教学岗；顺序按学科惯例排列，前端直接照此渲染。
SUBJECTS: tuple[str, ...] = (
    "语文", "数学", "英语", "物理", "化学", "生物",
    "政治", "历史", "地理", "道德与法治",
    "体育", "音乐", "美术", "信息技术", "通用技术",
    "科学", "心理健康", "劳动", "幼儿教育", "特殊教育",
)

# 公告里的常见写法归一到上面的标准名。
# 没有这层映射，"心理教师"这类写法就识别不出学科，岗位的 subject 会是 NULL——
# 库里现在有 12 条（11%）就是这么丢的，无论前端怎么筛都出不来。
SUBJECT_ALIASES: dict[str, str] = {
    "心理": "心理健康",
    "心理健康教育": "心理健康",
    "学前教育": "幼儿教育",
    "幼教": "幼儿教育",
    "体育与健康": "体育",
    "思想政治": "政治",
    "信息科技": "信息技术",
}


def normalize_subject(raw: str | None) -> str | None:
    """把公告里的写法归一到标准学科名。认不出就原样返回。"""
    if not raw:
        return None
    return SUBJECT_ALIASES.get(raw.strip(), raw.strip())


# 按学段顺序排列。"中小学"是爬虫无法判定具体学段时的兜底值，
# 属数据产物而非求职意向，故不列为可选项。
STAGES: tuple[str, ...] = ("幼儿园", "小学", "初中", "高中", "中职")

# 深圳市全部行政区与功能区。
DISTRICTS: tuple[str, ...] = (
    "福田区", "罗湖区", "南山区", "盐田区", "宝安区", "龙岗区",
    "龙华区", "坪山区", "光明区", "大鹏新区", "深汕特别合作区",
)

SCHOOL_TYPES: tuple[str, ...] = ("公办", "民办", "培训机构")

# 公告里常用简称，需归一到上面的标准名，否则识别不到。
